#!/usr/bin/env bash
# Mints EmberKV API keys for local development and writes:
#   .dev/emberkv-auth.toml   hashes only, mounted into / read by emberkv-server
#   .env.local               EMBERKV_TOKEN / EMBERKV_ADMIN_TOKEN for the ERP
#
# Uses `ekv` from the sibling ../emberkv checkout (built on demand), or from
# the emberkv Docker image when cargo is unavailable. Idempotent: existing
# keys are kept.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EMBERKV_DIR="${EMBERKV_DIR:-$ROOT/../emberkv}"
AUTH_FILE="$ROOT/.dev/emberkv-auth.toml"
ENV_FILE="$ROOT/.env.local"
NAMESPACES="sessions,limits,idempotency,locks,cache"

if [[ -f "$AUTH_FILE" ]] && grep -q '^EMBERKV_TOKEN=' "$ENV_FILE" 2>/dev/null; then
  echo "EmberKV keys already exist ($AUTH_FILE). Delete it to rotate."
  exit 0
fi

ekv() {
  if [[ -x "$EMBERKV_DIR/target/release/ekv" ]]; then
    "$EMBERKV_DIR/target/release/ekv" "$@"
  elif command -v cargo >/dev/null; then
    cargo run -q --release --manifest-path "$EMBERKV_DIR/Cargo.toml" -p emberkv-cli -- "$@"
  else
    docker compose -f "$ROOT/compose.yaml" run --rm --no-deps --entrypoint ekv emberkv "$@"
  fi
}

mkdir -p "$ROOT/.dev"
app_out="$(ekv token --name kiln-erp --access read_write --namespaces "$NAMESPACES")"
admin_out="$(ekv token --name kiln-erp-ops --access admin --namespaces '*')"

{
  echo "# Generated by scripts/emberkv-setup.sh. Hashes only; tokens live in .env.local."
  sed -n '/^\[\[key\]\]/,$p' <<<"$app_out"
  echo
  sed -n '/^\[\[key\]\]/,$p' <<<"$admin_out"
} >"$AUTH_FILE"

touch "$ENV_FILE"
grep -v -E '^EMBERKV_(ADMIN_)?TOKEN=' "$ENV_FILE" >"$ENV_FILE.tmp" || true
{
  cat "$ENV_FILE.tmp"
  echo "EMBERKV_TOKEN=$(grep -o 'ekv_[0-9a-f]*' <<<"$app_out")"
  echo "EMBERKV_ADMIN_TOKEN=$(grep -o 'ekv_[0-9a-f]*' <<<"$admin_out")"
} >"$ENV_FILE"
rm "$ENV_FILE.tmp"
chmod 600 "$ENV_FILE" "$AUTH_FILE"

echo "✓ Wrote $AUTH_FILE and tokens to $ENV_FILE"
